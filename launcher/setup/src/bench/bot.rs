/// Largest decompressed packet accepted; vanilla allows 8 MiB.
const MAX_PACKET: usize = 8 << 20;
/// Chunks per tick the bot asks for after each batch, about what a fast vanilla client sends.
const DESIRED_CHUNKS_PER_TICK: f32 = 64.0;
const READ_POLL: Duration = Duration::from_millis(100);
const READ_CHUNK: usize = 64 * 1024;

#[derive(Debug, thiserror::Error)]
pub enum BotError {
    #[error("network: {0}")]
    Io(#[from] io::Error),
    #[error("protocol: {0}")]
    Protocol(String),
    #[error("disconnected by the server in {state}: {reason}")]
    Disconnected { state: &'static str, reason: String },
    #[error("the server asked for encryption; benchmarks need an offline-mode server")]
    OnlineMode,
    #[error("timed out in {0}")]
    Timeout(&'static str),
}

/// Milliseconds from the start of the TCP connect to each login milestone.
#[derive(Debug, Clone, Copy, Default, PartialEq)]
pub struct JoinTimings {
    pub login_finished_ms: f64,
    pub play_login_ms: f64,
    pub spawned_ms: f64,
}

pub struct Bot {
    conn: Conn,
    ids: PacketIds,
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum State {
    Login,
    Config,
    Play,
}

impl Bot {
    /// Logs in as `name` and returns once the server has sent the spawn position.
    ///
    /// # Errors
    /// Fails on network errors, protocol errors, a disconnect or `timeout`.
    pub fn join(
        addr: SocketAddr,
        name: &str,
        ids: PacketIds,
        timeout: Duration,
    ) -> Result<(Self, JoinTimings), BotError> {
        let start = Instant::now();
        let ms = || start.elapsed().as_secs_f64() * 1000.0;
        let stream = TcpStream::connect_timeout(&addr, timeout)?;
        stream.set_nodelay(true)?;
        stream.set_read_timeout(Some(READ_POLL))?;
        let mut bot = Self {
            conn: Conn::new(stream),
            ids,
        };
        let mut handshake = Vec::new();
        put_varint(&mut handshake, ids.protocol);
        put_string(&mut handshake, &addr.ip().to_string());
        handshake.extend_from_slice(&addr.port().to_be_bytes());
        put_varint(&mut handshake, 2);
        bot.conn.send(ids.sb_handshake, &handshake)?;
        let mut hello = Vec::new();
        put_string(&mut hello, name);
        hello.extend_from_slice(&offline_uuid(name));
        bot.conn.send(ids.sb_login_hello, &hello)?;

        let mut timings = JoinTimings::default();
        let mut state = State::Login;
        while start.elapsed() < timeout {
            let Some((id, body)) = bot.conn.read()? else {
                continue;
            };
            let mut r = Reader::new(&body);
            state = match state {
                State::Login => bot.on_login(id, &mut r, &mut timings, ms())?,
                State::Config => bot.on_config(id, &mut r)?,
                State::Play => {
                    if id == ids.cb_login {
                        timings.play_login_ms = ms();
                    }
                    if bot.on_play(id, &mut r)? {
                        timings.spawned_ms = ms();
                        bot.conn.send(ids.sb_player_loaded, &[])?;
                        return Ok((bot, timings));
                    }
                    State::Play
                }
            };
        }
        Err(BotError::Timeout(match state {
            State::Login => "login",
            State::Config => "configuration",
            State::Play => "play",
        }))
    }

    /// Keeps the connection alive until `until`.
    ///
    /// # Errors
    /// Fails on network or protocol errors and on a disconnect.
    pub fn pump_until(&mut self, until: Instant) -> Result<(), BotError> {
        while Instant::now() < until {
            if let Some((id, body)) = self.conn.read()? {
                self.on_play(id, &mut Reader::new(&body))?;
            }
        }
        Ok(())
    }

    fn on_login(
        &mut self,
        id: i32,
        r: &mut Reader<'_>,
        timings: &mut JoinTimings,
        now_ms: f64,
    ) -> Result<State, BotError> {
        let ids = self.ids;
        if id == ids.cb_login_compression {
            // A negative threshold turns compression off.
            self.conn.threshold = usize::try_from(r.varint()?).ok();
        } else if id == ids.cb_login_finished {
            timings.login_finished_ms = now_ms;
            self.conn.send(ids.sb_login_ack, &[])?;
            return Ok(State::Config);
        } else if id == ids.cb_login_encryption {
            return Err(BotError::OnlineMode);
        } else if id == ids.cb_login_disconnect {
            return Err(disconnected("login", r));
        } else if id == ids.cb_login_custom_query {
            let mut answer = Vec::new();
            put_varint(&mut answer, r.varint()?);
            answer.push(0);
            self.conn.send(ids.sb_login_custom_query_answer, &answer)?;
        } else if id == ids.cb_login_cookie_request {
            let mut answer = Vec::new();
            put_string(&mut answer, &r.string()?);
            answer.push(0);
            self.conn.send(ids.sb_login_cookie_response, &answer)?;
        }
        Ok(State::Login)
    }

    fn on_config(&mut self, id: i32, r: &mut Reader<'_>) -> Result<State, BotError> {
        let ids = self.ids;
        if id == ids.cb_cfg_known_packs {
            // Answer like a vanilla client of the same version: it knows every listed pack.
            self.conn.send(ids.sb_cfg_known_packs, r.rest())?;
        } else if id == ids.cb_cfg_keep_alive {
            self.conn.send(ids.sb_cfg_keep_alive, r.take(8)?)?;
        } else if id == ids.cb_cfg_ping {
            self.conn.send(ids.sb_cfg_pong, r.take(4)?)?;
        } else if id == ids.cb_cfg_code_of_conduct {
            self.conn.send(ids.sb_cfg_accept_code_of_conduct, &[])?;
        } else if id == ids.cb_cfg_cookie_request {
            let mut answer = Vec::new();
            put_string(&mut answer, &r.string()?);
            answer.push(0);
            self.conn.send(ids.sb_cfg_cookie_response, &answer)?;
        } else if id == ids.cb_cfg_resource_pack_push {
            let mut answer = r.take(16)?.to_vec();
            put_varint(&mut answer, 0);
            self.conn.send(ids.sb_cfg_resource_pack, &answer)?;
        } else if id == ids.cb_cfg_finish {
            self.conn.send(ids.sb_cfg_finish, &[])?;
            return Ok(State::Play);
        } else if id == ids.cb_cfg_disconnect {
            return Err(disconnected("configuration", r));
        }
        Ok(State::Config)
    }

    /// Handles one play packet; returns true for a position sync (a spawn or teleport).
    fn on_play(&mut self, id: i32, r: &mut Reader<'_>) -> Result<bool, BotError> {
        let ids = self.ids;
        if id == ids.cb_keep_alive {
            self.conn.send(ids.sb_keep_alive, r.take(8)?)?;
        } else if id == ids.cb_ping {
            self.conn.send(ids.sb_pong, r.take(4)?)?;
        } else if id == ids.cb_chunk_batch_finished {
            self.conn.send(
                ids.sb_chunk_batch_received,
                &DESIRED_CHUNKS_PER_TICK.to_be_bytes(),
            )?;
        } else if id == ids.cb_player_position {
            let mut answer = Vec::new();
            put_varint(&mut answer, r.varint()?);
            self.conn.send(ids.sb_accept_teleport, &answer)?;
            return Ok(true);
        } else if id == ids.cb_disconnect {
            return Err(disconnected("play", r));
        }
        Ok(false)
    }
}

/// Server-list ping; returns the status JSON.
///
/// # Errors
/// Fails on network or protocol errors or `timeout`.
pub fn status(addr: SocketAddr, ids: PacketIds, timeout: Duration) -> Result<String, BotError> {
    let start = Instant::now();
    let stream = TcpStream::connect_timeout(&addr, timeout)?;
    stream.set_read_timeout(Some(READ_POLL))?;
    let mut conn = Conn::new(stream);
    let mut handshake = Vec::new();
    put_varint(&mut handshake, ids.protocol);
    put_string(&mut handshake, &addr.ip().to_string());
    handshake.extend_from_slice(&addr.port().to_be_bytes());
    put_varint(&mut handshake, 1);
    conn.send(ids.sb_handshake, &handshake)?;
    conn.send(ids.sb_status_request, &[])?;
    while start.elapsed() < timeout {
        if let Some((id, body)) = conn.read()? {
            if id != ids.cb_status_response {
                return Err(BotError::Protocol(format!("unexpected status packet {id}")));
            }
            return Reader::new(&body).string();
        }
    }
    Err(BotError::Timeout("status"))
}

fn disconnected(state: &'static str, r: &Reader<'_>) -> BotError {
    BotError::Disconnected {
        state,
        reason: String::from_utf8_lossy(&r.rest()[..r.rest().len().min(200)]).into_owned(),
    }
}

/// Java's `UUID.nameUUIDFromBytes("OfflinePlayer:" + name)`, which vanilla uses offline.
#[must_use]
pub fn offline_uuid(name: &str) -> [u8; 16] {
    let mut h = md5_digest(format!("OfflinePlayer:{name}").as_bytes());
    h[6] = (h[6] & 0x0f) | 0x30;
    h[8] = (h[8] & 0x3f) | 0x80;
    h
}

fn md5_digest(data: &[u8]) -> [u8; 16] {
    md5::compute(data).0
}

fn put_varint(out: &mut Vec<u8>, value: i32) {
    let mut v = value.cast_unsigned();
    loop {
        let byte = u8::try_from(v & 0x7f).unwrap_or_default();
        v >>= 7;
        if v == 0 {
            out.push(byte);
            return;
        }
        out.push(byte | 0x80);
    }
}

fn put_string(out: &mut Vec<u8>, s: &str) {
    put_varint(out, i32::try_from(s.len()).unwrap_or(i32::MAX));
    out.extend_from_slice(s.as_bytes());
}

struct Reader<'a> {
    data: &'a [u8],
    pos: usize,
}

impl<'a> Reader<'a> {
    const fn new(data: &'a [u8]) -> Self {
        Self { data, pos: 0 }
    }

    fn varint(&mut self) -> Result<i32, BotError> {
        let mut result: u32 = 0;
        for shift in (0..35).step_by(7) {
            let byte = *self
                .data
                .get(self.pos)
                .ok_or_else(|| BotError::Protocol("truncated varint".into()))?;
            self.pos += 1;
            result |= u32::from(byte & 0x7f) << shift;
            if byte & 0x80 == 0 {
                return Ok(result.cast_signed());
            }
        }
        Err(BotError::Protocol("varint too long".into()))
    }

    fn take(&mut self, n: usize) -> Result<&'a [u8], BotError> {
        let end = self
            .pos
            .checked_add(n)
            .filter(|end| *end <= self.data.len())
            .ok_or_else(|| BotError::Protocol("truncated field".into()))?;
        let slice = &self.data[self.pos..end];
        self.pos = end;
        Ok(slice)
    }

    fn string(&mut self) -> Result<String, BotError> {
        let len = usize::try_from(self.varint()?)
            .map_err(|_| BotError::Protocol("negative string length".into()))?;
        Ok(String::from_utf8_lossy(self.take(len)?).into_owned())
    }

    fn rest(&self) -> &'a [u8] {
        &self.data[self.pos..]
    }
}

/// Removes one length-prefixed frame from the front of `buf`, if a whole one is there.
///
/// Frame lengths are at most three bytes (2 MiB), as in vanilla.
fn split_frame(buf: &mut Vec<u8>) -> Result<Option<Vec<u8>>, BotError> {
    let mut length: usize = 0;
    for (i, byte) in buf.iter().enumerate().take(3) {
        length |= usize::from(byte & 0x7f) << (7 * i);
        if byte & 0x80 == 0 {
            let start = i + 1;
            if buf.len() < start + length {
                return Ok(None);
            }
            let frame = buf[start..start + length].to_vec();
            buf.drain(..start + length);
            return Ok(Some(frame));
        }
    }
    if buf.len() >= 3 {
        return Err(BotError::Protocol("frame length varint too long".into()));
    }
    Ok(None)
}

struct Conn {
    stream: TcpStream,
    buf: Vec<u8>,
    /// Reused for every socket read.
    scratch: Vec<u8>,
    threshold: Option<usize>,
}

impl Conn {
    fn new(stream: TcpStream) -> Self {
        Self {
            stream,
            buf: Vec::new(),
            scratch: vec![0; READ_CHUNK],
            threshold: None,
        }
    }

    /// Reads one packet, or `None` if nothing complete arrived within the poll interval.
    fn read(&mut self) -> Result<Option<(i32, Vec<u8>)>, BotError> {
        loop {
            if let Some(frame) = split_frame(&mut self.buf)? {
                return self.decode(&frame).map(Some);
            }
            match self.stream.read(&mut self.scratch) {
                Ok(0) => {
                    return Err(BotError::Io(io::Error::new(
                        io::ErrorKind::UnexpectedEof,
                        "connection closed by the server",
                    )));
                }
                Ok(n) => self.buf.extend_from_slice(&self.scratch[..n]),
                Err(e)
                    if matches!(
                        e.kind(),
                        io::ErrorKind::WouldBlock | io::ErrorKind::TimedOut
                    ) =>
                {
                    return Ok(None);
                }
                Err(e) => return Err(e.into()),
            }
        }
    }

    fn decode(&self, frame: &[u8]) -> Result<(i32, Vec<u8>), BotError> {
        let mut r = Reader::new(frame);
        let body = if self.threshold.is_some() {
            let data_len = usize::try_from(r.varint()?)
                .map_err(|_| BotError::Protocol("negative data length".into()))?;
            if data_len == 0 {
                r.rest().to_vec()
            } else {
                if data_len > MAX_PACKET {
                    return Err(BotError::Protocol(format!("packet of {data_len} bytes")));
                }
                let mut out = Vec::with_capacity(data_len);
                ZlibDecoder::new(r.rest())
                    .take(u64::try_from(MAX_PACKET).unwrap_or(u64::MAX))
                    .read_to_end(&mut out)?;
                out
            }
        } else {
            r.rest().to_vec()
        };
        let mut r = Reader::new(&body);
        let id = r.varint()?;
        Ok((id, r.rest().to_vec()))
    }

    fn send(&mut self, id: i32, payload: &[u8]) -> Result<(), BotError> {
        let mut body = Vec::with_capacity(payload.len() + 5);
        put_varint(&mut body, id);
        body.extend_from_slice(payload);
        let framed_body = match self.threshold {
            Some(threshold) if body.len() >= threshold => {
                let mut packed = Vec::new();
                put_varint(&mut packed, i32::try_from(body.len()).unwrap_or(i32::MAX));
                let mut encoder = ZlibEncoder::new(packed, Compression::default());
                encoder.write_all(&body)?;
                encoder.finish()?
            }
            Some(_) => {
                let mut packed = vec![0];
                packed.extend_from_slice(&body);
                packed
            }
            None => body,
        };
        let mut frame = Vec::with_capacity(framed_body.len() + 5);
        put_varint(
            &mut frame,
            i32::try_from(framed_body.len()).unwrap_or(i32::MAX),
        );
        frame.extend_from_slice(&framed_body);
        self.stream.write_all(&frame)?;
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn varint_matches_the_protocol_examples() {
        // Examples from the protocol documentation.
        for (value, bytes) in [
            (0, vec![0x00]),
            (1, vec![0x01]),
            (127, vec![0x7f]),
            (128, vec![0x80, 0x01]),
            (255, vec![0xff, 0x01]),
            (25565, vec![0xdd, 0xc7, 0x01]),
            (2_147_483_647, vec![0xff, 0xff, 0xff, 0xff, 0x07]),
            (-1, vec![0xff, 0xff, 0xff, 0xff, 0x0f]),
        ] {
            let mut out = Vec::new();
            put_varint(&mut out, value);
            assert_eq!(out, bytes, "{value}");
            assert_eq!(Reader::new(&bytes).varint().unwrap(), value);
        }
    }

    #[test]
    fn offline_uuid_matches_java() {
        // UUID.nameUUIDFromBytes("OfflinePlayer:Notch") = b50ad385-829d-3141-a216-7e7d7539ba7f
        let expected = [
            0xb5, 0x0a, 0xd3, 0x85, 0x82, 0x9d, 0x31, 0x41, 0xa2, 0x16, 0x7e, 0x7d, 0x75, 0x39,
            0xba, 0x7f,
        ];
        assert_eq!(offline_uuid("Notch"), expected);
    }

    #[test]
    fn truncated_fields_are_errors() {
        assert!(Reader::new(&[0x80]).varint().is_err());
        assert!(Reader::new(&[0xff; 6]).varint().is_err());
        assert!(Reader::new(&[1, 2]).take(3).is_err());
    }

    #[test]
    fn frames_split_only_when_complete() {
        // Two frames: [3: a b c] and [1: d], then the first byte of a third.
        let mut buf = vec![3, b'a', b'b', b'c', 1, b'd', 2];
        assert_eq!(split_frame(&mut buf).unwrap(), Some(b"abc".to_vec()));
        assert_eq!(split_frame(&mut buf).unwrap(), Some(b"d".to_vec()));
        assert_eq!(split_frame(&mut buf).unwrap(), None);
        assert_eq!(buf, vec![2]);
    }

    #[test]
    fn four_byte_frame_length_is_rejected() {
        let mut buf = vec![0xff, 0xff, 0xff, 0x01];
        assert!(split_frame(&mut buf).is_err());
    }
}
